import Link from "next/link";
import { fetchPublishedPosts } from "@/lib/api";

export const dynamic = "force-dynamic";

function formatDate(iso: string | null): string {
  if (!iso) return "Unscheduled";
  return new Date(iso).toLocaleString("en-US", {
    dateStyle: "medium",
    timeStyle: "short",
  });
}

export default async function HomePage() {
  const posts = await fetchPublishedPosts();

  return (
    <div className="space-y-8">
      <section className="space-y-3">
        <h1 className="text-3xl font-bold tracking-tight text-white">
          Published LLM Security Audits
        </h1>
        <p className="max-w-2xl text-sm leading-relaxed text-slate-400">
          Every report below is generated by our multi-agent red-teaming
          pipeline under strict LiteLLM budget guardrails and isolated Docker
          sandboxes, then rendered as sanitized Markdown.
        </p>
      </section>

      {posts.length === 0 ? (
        <div className="rounded-xl border border-slate-800 bg-slate-900/50 p-8 text-center">
          <p className="text-sm text-slate-300">
            No published audit reports yet. Trigger a cycle via{" "}
            <code className="rounded bg-slate-800 px-1.5 py-0.5 text-emerald-400">
              POST /api/trigger-demo
            </code>
            .
          </p>
        </div>
      ) : (
        <ul className="space-y-4">
          {posts.map((post) => (
            <li
              key={post.id}
              className="rounded-xl border border-slate-800 bg-slate-900/60 p-6 transition hover:border-emerald-500/50"
            >
              <div className="flex flex-wrap items-center justify-between gap-2 text-xs text-slate-400">
                <time dateTime={post.published_at ?? undefined}>
                  {formatDate(post.published_at)}
                </time>
                <span className="rounded bg-emerald-500/10 px-2 py-0.5 font-mono text-emerald-400">
                  published
                </span>
              </div>
              <h2 className="mt-2 text-xl font-semibold text-white">
                <Link
                  href={`/posts/${post.slug}`}
                  className="hover:text-emerald-400"
                >
                  {post.title}
                </Link>
              </h2>
              <p className="mt-2 text-sm leading-relaxed text-slate-300">
                {post.summary}
              </p>
              <div className="mt-4">
                <Link
                  href={`/posts/${post.slug}`}
                  className="text-sm font-medium text-emerald-400 hover:text-emerald-300"
                >
                  Read full report &rarr;
                </Link>
              </div>
            </li>
          ))}
        </ul>
      )}
    </div>
  );
}
